const BiblicalWhatAwaits = () => {
  const [openIndex, setOpenIndex] = useState<number | null>(null);

  const toggle = (i: number) => setOpenIndex(openIndex === i ? null : i);

  return (
    <section className={styles.section} id="what">
      <div className={styles.secHead}>
        <span className={styles.label}>01 — Почему стоит</span>
        <h2 className={styles.h2}>Что тебя ждёт?</h2>
      </div>
      <div className={styles.acc}>
        {items.map((item, i) => (
          <div key={item.num} className={styles.item}>
            <button className={styles.accHead} onClick={() => toggle(i)}>
              <span className={styles.num}>{item.num}</span>
              <span
                className={`${styles.accTitle} ${openIndex === i ? styles.accTitleOpen : ''}`}
              >
                {item.title}
              </span>
              <span
                className={`${styles.accPlus} ${openIndex === i ? styles.accPlusOpen : ''}`}
              />
            </button>
            <AnimatePresence initial={false}>
              {openIndex === i && (
                <motion.div
                  key="body"
                  initial={{ height: 0, opacity: 0 }}
                  animate={{ height: 'auto', opacity: 1 }}
                  exit={{ height: 0, opacity: 0 }}
                  transition={{ duration: 0.35, ease: 'easeInOut' }}
                  style={{ overflow: 'hidden' }}
                >
                  <p className={styles.bodyText}>{item.body}</p>
                </motion.div>
              )}
            </AnimatePresence>
          </div>
        ))}
      </div>
    </section>
  );
};

